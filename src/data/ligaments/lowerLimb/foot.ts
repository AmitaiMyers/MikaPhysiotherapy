const ARCH_MUSCLES = ['tibialis-posterior', 'fibularis-longus', 'flexor-hallucis-longus', 'flexor-digitorum-longus', 'abductor-hallucis', 'flexor-digitorum-brevis', 'quadratus-plantae'];
const INTRINSICS = ['abductor-hallucis', 'flexor-digitorum-brevis', 'quadratus-plantae', 'lumbricals-foot', 'plantar-interossei', 'dorsal-interossei-foot', 'flexor-hallucis-brevis', 'adductor-hallucis'];
const PLANTAR_NERVES = ['medial-plantar', 'lateral-plantar'];
const ARCH_REHAB = ['short-foot', 'towel-curl', 'toe-yoga', 'calf-raise', 'single-leg-calf-raise', 'single-leg-stance'];
const SMALL_LIGAMENT_HEALING = 'Small intertarsal ligaments heal in about 4–8 weeks; pain on loading the midfoot settles with a stiff-soled shoe or boot and graded return.';

/** Small dorsal or plantar ligaments of the midfoot and forefoot share most of their description. */
function smallFootLigament(fields: {
  id: string;
  name: string;
  latinName: string;
  group: typeof MIDFOOT | typeof FOREFOOT;
  jointIds: string[];
  surface: 'dorsal' | 'plantar' | 'interosseous';
  bones: string[];
  between: string;
  restraints: Ligament['restraints'];
  clinical: string[];
  synonyms?: string[];
}): Ligament {
  const surfaceText = { dorsal: 'on the top of the foot', plantar: 'on the sole', interosseous: 'deep between the bones' }[fields.surface];
  return ligament({
    ...fields.group,
    id: fields.id,
    name: fields.name,
    latinName: fields.latinName,
    synonyms: fields.synonyms ?? [],
    kind: 'ligament',
    jointIds: fields.jointIds,
    summary: `Short bands ${surfaceText} joining ${fields.between}.`,
    structure: [
      fields.surface === 'plantar'
        ? 'Thicker and stronger than their dorsal counterparts, reinforced by the tendons of fibularis longus and tibialis posterior.'
        : fields.surface === 'dorsal'
          ? 'Thin, flat bands under the extensor tendons; weaker than the plantar ligaments.'
          : 'Strong short fibres filling the space between the bones, the strongest of the three layers.',
    ],
    attachments: [{ end: 'Between', text: `Adjacent surfaces of ${fields.between}`, bones: fields.bones }],
    functions: ['Hold the bones of the arch together so the foot works as a rigid lever in push-off and a flexible adapter in early stance.'],
    restraints: fields.restraints,
    protectiveMuscleIds: fields.surface === 'dorsal' ? ['extensor-digitorum-brevis', 'tibialis-anterior'] : ARCH_MUSCLES,
    nerveIds: fields.surface === 'dorsal' ? ['deep-fibular'] : PLANTAR_NERVES,
    healing: SMALL_LIGAMENT_HEALING,
    clinical: fields.clinical,
    sourceIds: ANATOMY,
  });
}

