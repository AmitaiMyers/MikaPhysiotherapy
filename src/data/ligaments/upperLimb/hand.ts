/** Carpometacarpal and metacarpal ligaments share most of their description. */
function metacarpalLigament(fields: { id: string; name: string; latinName: string; surface: 'dorsal' | 'palmar' | 'interosseous'; jointIds: string[]; bones: string[]; between: string; restraints: Ligament['restraints']; clinical: string[] }): Ligament {
  const where = { dorsal: 'on the back of the hand', palmar: 'on the palm side', interosseous: 'deep between the bones' }[fields.surface];
  return ligament({
    ...HAND,
    jointIds: fields.jointIds,
    id: fields.id,
    name: fields.name,
    latinName: fields.latinName,
    kind: 'ligament',
    summary: `Short bands ${where} joining ${fields.between}.`,
    structure: [
      fields.surface === 'interosseous' ? 'Short, strong fibres between the adjacent bones, the strongest of the three layers.' : `Flat bands ${where}; the CMC joints of the index and middle fingers are almost rigid, the ring and little fingers more mobile.`,
    ],
    attachments: [{ end: 'Between', text: `Adjacent surfaces of ${fields.between}`, bones: fields.bones }],
    functions: ['Make the index and middle metacarpals a stable central pillar of the hand while allowing the ring and little metacarpals to flex for cupping the palm and gripping.'],
    restraints: fields.restraints,
    protectiveMuscleIds: fields.surface === 'dorsal' ? ['extensor-carpi-radialis-longus', 'extensor-carpi-radialis-brevis', 'extensor-carpi-ulnaris'] : ['flexor-carpi-radialis', 'opponens-digiti-minimi-hand', 'palmar-interossei'],
    nerveIds: fields.surface === 'dorsal' ? ['posterior-interosseous'] : ['ulnar-deep'],
    healing: 'Sprains heal in 4–6 weeks; CMC dislocations (often of the ring and little finger with a punch) need reduction and fixation.',
    injuryMechanisms: ['Punching or falling on the clenched fist'],
    clinical: fields.clinical,
    exerciseIds: ['putty-grip', 'wrist-weight-bearing'],
    sourceIds: ANATOMY,
  });
}

