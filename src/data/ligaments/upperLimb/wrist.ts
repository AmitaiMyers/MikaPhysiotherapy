const CARPAL_HEALING =
  'Partial carpal ligament injuries usually settle in 6–12 weeks with a splint and graded loading; complete scapholunate or lunotriquetral tears heal poorly without surgery and are best repaired within about 6 weeks.';

/** Small intercarpal and radiocarpal ligaments share most of their description. */
function carpalLigament(fields: {
  id: string;
  name: string;
  latinName: string;
  surface: 'dorsal' | 'palmar';
  bones: string[];
  from: string;
  to: string;
  summary: string;
  functions: string[];
  restraints: Ligament['restraints'];
  clinical: string[];
  synonyms?: string[];
}): Ligament {
  return ligament({
    ...WRIST,
    jointIds: ['wrist'],
    id: fields.id,
    name: fields.name,
    latinName: fields.latinName,
    synonyms: fields.synonyms ?? [],
    kind: 'ligament',
    summary: fields.summary,
    structure: [
      fields.surface === 'palmar'
        ? 'An intracapsular palmar ligament: thick, strong and the main stabiliser of its part of the carpus (palmar ligaments are stronger than dorsal ones).'
        : 'An intracapsular dorsal ligament: thinner than the palmar ligaments but rich in proprioceptive nerve endings.',
    ],
    attachments: [
      { end: 'From', text: fields.from, bones: [fields.bones[0] as string] },
      { end: 'To', text: fields.to, bones: fields.bones.slice(1) },
    ],
    functions: fields.functions,
    restraints: fields.restraints,
    protectiveMuscleIds: WRIST_STABILISERS,
    nerveIds: fields.surface === 'dorsal' ? ['posterior-interosseous'] : ['anterior-interosseous', 'ulnar'],
    healing: CARPAL_HEALING,
    injuryMechanisms: ['Fall on the outstretched hand with the wrist extended'],
    clinical: fields.clinical,
    exerciseIds: WRIST_REHAB,
    sourceIds: ANATOMY,
  });
}

